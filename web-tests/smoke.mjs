// Opens the web app in a real (headless) Chrome and clicks through it. No network needed.
import { chromium } from 'playwright';
const url = process.argv[2] || 'http://localhost:8765/index.html';
const b = await chromium.launch();
const p = await b.newPage({ viewport: { width: 390, height: 844 } });
const errors = [];
p.on('pageerror', (e) => errors.push(e.message));
await p.route(/^https?:\/\/(?!localhost)/, (r) => r.abort()); // offline: only the app itself
await p.goto(url);
await p.waitForFunction(() => window.radiocast && document.querySelectorAll('.row').length > 0, null, { timeout: 10000 });
const check = (ok, what) => { if (!ok) { errors.push('Misslyckades: ' + what); } else console.log('ok  ' + what); };
await p.waitForTimeout(900);
check(await p.isHidden('#sheet'), 'ingen ruta i vägen vid första besöket');
check(await p.locator('.row').count() === 6, 'listan visar 6 kanaler');
await p.click('#searchBar');
check(await p.isVisible('#search'), 'sökfönstret öppnas');
check(await p.locator('#genres .gchip').count() === 12, 'genreknapparna finns');
await p.click('#searchBack');
check(await p.isHidden('#listhead'), 'sortering och Klar är dolda utanför redigering');
await p.click('#menuBtn'); await p.waitForTimeout(300);
await p.click('text=Redigera listan'); await p.waitForTimeout(400);
await p.click('#orderOwn');
check(await p.locator('.grip').count() === 6, 'redigeringsläget (från menyn) visar handtag');
await p.click('#editBtn');
check(await p.isHidden('#listhead'), 'Klar avslutar redigeringen');
check(await p.isVisible('#installBtn'), 'knappen för hemskärmen syns');
// Back/forward on the lock screen, headphones and in the car: the next channel in the list's order.
const order = await p.evaluate(() => window.radiocast.listOrder().map((s) => s.name));
const visible = await p.$$eval('.row .name', (n) => n.map((x) => x.textContent));
check(order.join('|') === visible.join('|'), 'kanalordningen följer listan');
await p.evaluate(() => { window.radiocast.stepChannel(1); });
const first = await p.evaluate(() => window.radiocast.nowPlaying && window.radiocast.nowPlaying.name);
await p.evaluate(() => { window.radiocast.stepChannel(1); window.radiocast.stepChannel(-1); });
check(first && (await p.evaluate(() => window.radiocast.nowPlaying.name)) === first, 'nästa/föregående kanal fungerar');
await p.click('.row >> nth=0');
check(await p.isVisible('#np'), 'spelarkortet visas efter tryck på en kanal');
await p.click('#npText');
check(await p.isVisible('#sheet'), 'låtvyn öppnas');
await p.click('#sheetClose'); await p.waitForTimeout(300);
check(await p.isHidden('#sheet'), 'låtvyn stängs med ✕');
await p.click('#menuBtn');
check((await p.textContent('#sheetBody')).includes('Dela appen med en vän'), 'menyn öppnas');
await p.click('text=Dela appen med en vän'); await p.waitForTimeout(500);
check((await p.textContent('#sheetBody')).includes('Med mina kanaler'), 'dela appen erbjuder med eller utan kanaler');
// Restarted while the radio played on a speaker: the app says where it probably plays.
const p2 = await b.newPage();
p2.on('pageerror', (e) => errors.push(e.message));
await p2.route(/^https?:\/\/(?!localhost)/, (r) => r.abort());
await p2.addInitScript(() => localStorage.setItem('rc.castingOn',
  JSON.stringify({ device: 'Kök', url: 'https://live1.sr.se/p3-aac-320', at: Date.now() })));
await p2.goto(url);
await p2.waitForTimeout(5500);
check((await p2.textContent('#outText')) === 'Kök', 'efter omstart visar högtalarknappen Kök');
await p2.click('#outBtn'); await p2.waitForTimeout(400);
check((await p2.textContent('#sheetBody')).includes('Använd telefonen'), 'högtalarknappen erbjuder anslut igen eller telefonen');
check((await p2.textContent('#npStatus')).includes('troligen på Kök'), 'efter omstart: "spelar troligen på Kök"');
// A shared "listen" link offers the channel.
const p3 = await b.newPage();
p3.on('pageerror', (e) => errors.push(e.message));
await p3.route(/^https?:\/\/(?!localhost)/, (r) => r.abort());
await p3.goto(url + '#lyssna=' + encodeURIComponent('https://icecast.radiofrance.fr/fip-midfi.mp3') + '&namn=FIP');
await p3.waitForTimeout(500);
check((await p3.textContent('#snackText')).includes('FIP'), 'delad kanallänk erbjuder kanalen');
check((await p3.textContent('#outText')) === 'Telefon', 'Telefon är vald från början');
check(await p.isVisible('#volume'), 'dator: volymreglaget finns kvar');
// Phone: no slider (it only stacks on the media volume); a lowered one fades in to full once.
const pc = await b.newContext({ viewport: { width: 390, height: 844 }, isMobile: true, hasTouch: true });
const p4 = await pc.newPage();
p4.on('pageerror', (e) => errors.push(e.message));
await p4.route(/^https?:\/\/(?!localhost)/, (r) => r.abort());
await p4.addInitScript(() => { if (!localStorage.getItem('rc.volumeMoved')) localStorage.setItem('rc.volume', '20'); });
await p4.goto(url);
await p4.waitForFunction(() => window.radiocast && document.querySelectorAll('.row').length > 0, null, { timeout: 10000 });
await p4.waitForTimeout(900);
await p4.click('.row >> nth=0');
await p4.waitForTimeout(300);
check(await p4.isHidden('#volume') && await p4.isVisible('#volHint'), 'telefon: inget reglage, "telefonens knappar" i stället');
check((await p4.textContent('#snackText')).includes('telefonens knappar'), 'telefon: säger en gång att volymen flyttat');
const v0 = await p4.evaluate(() => window.radiocast.audioVolume);
check(v0 < 0.5, 'telefon: börjar på gamla nivån, inte högt direkt (' + v0.toFixed(2) + ')');
await p4.waitForTimeout(8500);
check((await p4.evaluate(() => window.radiocast.audioVolume)) === 1, 'telefon: tonar upp till full nivå');
await p4.reload();
await p4.waitForFunction(() => window.radiocast && document.querySelectorAll('.row').length > 0, null, { timeout: 10000 });
await p4.click('.row >> nth=0'); await p4.waitForTimeout(300);
check(!(await p4.textContent('#snackText')).includes('telefonens knappar'), 'telefon: meddelandet visas bara en gång');
check((await p4.evaluate(() => window.radiocast.audioVolume)) === 1, 'telefon: full nivå direkt nästa gång');
await b.close();
if (errors.length) { console.error(errors.join('\n')); process.exit(1); }
console.log('Allt gick bra.');
